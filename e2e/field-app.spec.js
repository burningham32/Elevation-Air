test('production app works offline after first load and backup restores inspection',async({page,context})=>{
 await inspect(page);await expect(page.locator('#save-status')).toHaveText('Saved on this device');
 await page.evaluate(()=>navigator.serviceWorker.ready);
 await page.reload();
 await context.setOffline(true);await page.reload();
 await expect(page.locator('[data-path="name"]')).toHaveValue('Alex Morgan');
 await page.locator('[data-tab="settings"]').click();
 const downloadPromise=page.waitForEvent('download');await page.locator('#export').click();const download=await downloadPromise;const path=await download.path();
 await context.setOffline(false);
 await page.locator('#new').click();await expect(page.locator('[data-path="name"]')).toHaveValue('');
 await page.locator('[data-tab="settings"]').click();page.once('dialog',d=>d.accept());await page.locator('#import').setInputFiles(path);await expect(page.locator('#toast')).toContainText('Backup imported');
 await page.locator('#jobs').click();await page.locator('.job-open').filter({hasText:'Alex Morgan'}).click();await expect(page.locator('[data-path="name"]')).toHaveValue('Alex Morgan');
});

