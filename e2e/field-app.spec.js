import {test,expect} from '@playwright/test';
async function inspect(page){
 await page.goto('./');
 await page.locator('[data-path="name"]').fill('Alex Morgan');
 await page.locator('[data-path="address"]').fill('123 Mountain View Drive');
 await page.locator('[data-path="phone"]').fill('303-555-0142');
 await page.locator('[data-path="levels.0.sqft"]').fill('2000');
 await page.locator('[data-path="atticSqft"]').fill('1500');
 await page.locator('[data-path="notes"]').fill('Soffit intake is obstructed. Customer reports warm upstairs bedrooms.');
 await page.locator('[data-path="notes"]').blur();
}
test('inspection persists and produces a correctly priced draft proposal on desktop',async({page})=>{
 const errors=[];page.on('pageerror',e=>errors.push(e.message));
 await inspect(page);
 await expect(page.locator('#summary')).toContainText('10.00 ft²');
 await expect(page.locator('#save-status')).toHaveText('Saved on this device');
 await page.reload();await expect(page.locator('[data-path="name"]')).toHaveValue('Alex Morgan');
 await page.getByRole('button',{name:'Review recommendations'}).click();
 await expect(page.locator('.model-name').first()).toContainText('Trident Pro 4.8');
 await page.locator('[data-path="includeAttic"]').uncheck();
 await expect(page.locator('.price-total')).toContainText('$2,100.00');
 await page.locator('[data-path="wholeSeries"]').selectOption('stealth');
 await expect(page.locator('.model-name').first()).toContainText('Stealth Pro 4.8');
 await expect(page.locator('.price-total')).toContainText('$2,400.00');
 await page.getByRole('button',{name:'Generate proposal',exact:false}).last().click();
 await expect(page.locator('#proposal-document')).toContainText('Alex Morgan');
 await expect(page.locator('#proposal-document')).toContainText('Stealth Pro 4.8');
 await expect(page.locator('#proposal-document .price-total')).toContainText('$2,400.00');
 await expect(page.locator('.draft-label')).toHaveText('DRAFT · REVIEW REQUIRED');
 await page.screenshot({path:'/tmp/elevation-proposal.png',fullPage:true});
 await page.pdf({path:'/tmp/elevation-proposal.pdf',format:'Letter',printBackground:true});
 expect(errors).toEqual([]);
});
